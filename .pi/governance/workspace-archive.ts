import { createHash, randomUUID } from "node:crypto";
import * as fs from "node:fs";
import * as path from "node:path";
import { dataRoot, type GovernanceStore, primaryWorktree } from "./store.ts";
import type { GovernanceEvent, GovernanceEventInput, GovernanceState } from "./types.ts";

type SnapshotFile = { path: string; sha256: string };
type SnapshotManifest = {
	projectId: string;
	createdAt: string;
	preArchiveSequence: number;
	files: SnapshotFile[];
};

const digest = (value: Buffer | string): string => createHash("sha256").update(value).digest("hex");
const active = (state: string): boolean =>
	state === "CREATED" || state === "RUNNING" || state === "PAUSED" || state === "INTERRUPTED";
const generatedDocument = "<!-- Generated by Agent Governance from the event ledger. Do not edit as an approval. -->\n";

function collect(root: string, relative: string, files: string[]): void {
	const target = path.join(root, relative);
	if (!fs.existsSync(target)) return;
	const stat = fs.lstatSync(target);
	if (stat.isSymbolicLink()) throw new Error(`Workspace archive refuses symbolic link: ${relative}`);
	if (stat.isFile()) {
		files.push(relative);
		return;
	}
	if (!stat.isDirectory()) throw new Error(`Workspace archive refuses special file: ${relative}`);
	for (const entry of fs.readdirSync(target).sort()) collect(root, path.join(relative, entry), files);
}

function snapshotPaths(project: string): string[] {
	const files: string[] = [];
	for (const directory of ["management", ".pi/agents", ".pi/governance"]) collect(project, directory, files);
	for (const name of [".pi/settings.json", ".pi/provider-profiles.json", ".pi/extensions/governance-bridge.ts"])
		collect(project, name, files);
	for (const name of ["docs/PRD.md", "docs/PROJECT-PLAN.md"]) {
		const file = path.join(project, name);
		if (!fs.existsSync(file)) continue;
		if (!fs.readFileSync(file, "utf8").startsWith(generatedDocument))
			throw new Error(`Workspace archive refuses to replace user document: ${name}`);
		collect(project, name, files);
	}
	return files.sort();
}

/**
 * Archive one governed Git project as a single epoch. The snapshot is made while
 * the ledger writer lock is held, before the archive event is appended. If the
 * snapshot fails, no event is written. File cleanup is recoverable by rendering
 * views again; the source files remain until the complete snapshot exists.
 */
export function archiveWorkspace(
	project: string,
	store: GovernanceStore,
	input: { actor: string; reason: string; confirm: string },
): GovernanceEvent {
	if (!input.actor.trim() || !input.reason.trim() || !input.confirm.trim())
		throw new Error("Actor, archive reason and project ID confirmation are required");
	const root = fs.realpathSync(project);
	if (root !== fs.realpathSync(primaryWorktree(root)))
		throw new Error("Workspace archive must run from the primary Git worktree");
	if (fs.realpathSync(dataRoot(root)) !== fs.realpathSync(store.root))
		throw new Error("Workspace archive store does not belong to this project");
	const archiveId = `W-${randomUUID()}`;
	const timestamp = new Date().toISOString().replace(/[:.]/g, "-");
	const destination = path.join(store.root, "workspace-archives", `${timestamp}-${archiveId}`);
	const event: GovernanceEventInput = {
		type: "workspace.archived",
		actor: input.actor,
		taskId: null,
		runId: null,
		delegationId: null,
		payload: { archiveId, archiveReason: input.reason },
	};
	return store.append(event, (state) => {
		const projectId = state.events.find((entry) => entry.type === "project.initialized")?.payload.projectId;
		if (projectId !== input.confirm) throw new Error(`Confirmation must be the project id: ${String(projectId)}`);
		const live = Object.values(state.runs)
			.filter((run) => active(run.state))
			.map((run) => run.runId);
		if (live.length) throw new Error(`Active Runs must be reconciled before archiving: ${live.join(", ")}`);
		if (!state.projectApproved && !state.projectDraft && !Object.keys(state.tasks).length)
			throw new Error("Nothing to archive: current workspace already has no Project or Tasks");
		const files = snapshotPaths(root);
		fs.mkdirSync(path.dirname(destination), { recursive: true, mode: 0o700 });
		fs.mkdirSync(destination, { mode: 0o700 });
		const ledger = path.join(store.root, "events.jsonl");
		const ledgerCopy = path.join(destination, "events.jsonl");
		fs.copyFileSync(ledger, ledgerCopy, fs.constants.COPYFILE_EXCL);
		const ledgerSha256 = digest(fs.readFileSync(ledgerCopy));
		const snapshots: SnapshotFile[] = [];
		for (const relative of files) {
			const source = path.join(root, relative);
			const target = path.join(destination, "files", relative);
			fs.mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
			fs.copyFileSync(source, target, fs.constants.COPYFILE_EXCL);
			const sha256 = digest(fs.readFileSync(target));
			if (sha256 !== digest(fs.readFileSync(source))) throw new Error(`File changed during snapshot: ${relative}`);
			snapshots.push({ path: relative, sha256 });
		}
		const manifest: SnapshotManifest = {
			projectId,
			createdAt: new Date().toISOString(),
			preArchiveSequence: state.events.at(-1)?.sequence ?? 0,
			files: snapshots,
		};
		const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
		fs.writeFileSync(path.join(destination, "manifest.json"), manifestText, { flag: "wx", mode: 0o600 });
		for (const file of [
			ledgerCopy,
			path.join(destination, "manifest.json"),
			...files.map((name) => path.join(destination, "files", name)),
		]) {
			const fd = fs.openSync(file, "r");
			try {
				fs.fsyncSync(fd);
			} finally {
				fs.closeSync(fd);
			}
		}
		event.payload.snapshotReference = { path: destination, ledgerSha256, manifestSha256: digest(manifestText) };
		event.payload.archiveBoundary = manifest.preArchiveSequence + 1;
		event.payload.archivedRecordCounts = {
			tasks: Object.keys(state.tasks).length,
			delegations: Object.keys(state.delegations).length,
			runs: Object.keys(state.runs).length,
			workspaces: Object.keys(state.workspaces).length,
			decisions: Object.keys(state.decisions).length,
			deliverables: Object.keys(state.deliverables).length,
			verifications: Object.keys(state.verifications).length,
			accepted: Object.keys(state.accepted).length,
		};
	});
}

/** Finish an interrupted cleanup only for files whose bytes match the snapshot. */
export function finalizeWorkspaceArchive(project: string, state: GovernanceState): void {
	const event = state.events.findLast((entry) => entry.type === "workspace.archived");
	if (!event) return;
	const reference = event.payload.snapshotReference as
		| { path?: string; manifestSha256?: string; ledgerSha256?: string }
		| undefined;
	if (!reference?.path || !reference.manifestSha256)
		throw new Error("Workspace archive snapshot reference is missing");
	const archiveRoot = path.resolve(dataRoot(project), "workspace-archives");
	const destination = path.resolve(reference.path);
	if (!destination.startsWith(`${archiveRoot}${path.sep}`))
		throw new Error("Workspace archive path is outside ledger data");
	const complete = path.join(destination, "cleanup-complete");
	if (fs.existsSync(complete)) return;
	const manifestText = fs.readFileSync(path.join(destination, "manifest.json"), "utf8");
	if (digest(manifestText) !== reference.manifestSha256)
		throw new Error("Workspace archive manifest SHA-256 mismatch");
	const manifest = JSON.parse(manifestText) as SnapshotManifest;
	const removable = manifest.files.filter(
		(entry) =>
			(entry.path.startsWith(`management${path.sep}`) &&
				!entry.path.startsWith(`management${path.sep}policies${path.sep}`) &&
				entry.path !== path.join("management", "README.md")) ||
			entry.path === path.join("docs", "PRD.md") ||
			entry.path === path.join("docs", "PROJECT-PLAN.md"),
	);
	for (const entry of removable) {
		const file = path.join(project, entry.path);
		if (!fs.existsSync(file)) continue;
		if (fs.lstatSync(file).isSymbolicLink() || digest(fs.readFileSync(file)) !== entry.sha256)
			throw new Error(`Workspace archive cleanup conflict: ${entry.path}`);
	}
	for (const entry of removable) fs.rmSync(path.join(project, entry.path), { force: true });
	for (const directory of ["management/project", "management/tasks", "management/views"]) {
		const full = path.join(project, directory);
		if (!fs.existsSync(full)) continue;
		for (const entry of fs.readdirSync(full)) {
			const child = path.join(full, entry);
			if (fs.statSync(child).isDirectory() && fs.readdirSync(child).length === 0) fs.rmdirSync(child);
		}
	}
	fs.writeFileSync(complete, `${event.sequence}\n`, { flag: "wx", mode: 0o600 });
}
